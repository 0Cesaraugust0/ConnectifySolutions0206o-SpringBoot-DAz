-- Additive production schema for the Developer console.
-- Keep existing registration dates unknown; do not backfill historical users.
set local lock_timeout = '5s';
set local statement_timeout = '30s';

alter table connectify.user_accounts
    add column if not exists created_at timestamp(6) with time zone;

comment on column connectify.user_accounts.created_at is
    'Account registration instant. NULL means the historical registration date is unknown.';

create table connectify.account_access_audits (
    id bigint generated by default as identity primary key,
    actor_email varchar(255) not null,
    target_email varchar(255) not null,
    action varchar(255) not null,
    detail varchar(1000) not null,
    created_at timestamp(6) with time zone not null default now()
);

create index ix_account_access_audits_created_at
    on connectify.account_access_audits (created_at desc);

alter table connectify.account_access_audits enable row level security;
revoke all on connectify.account_access_audits from public, anon, authenticated;
revoke all on sequence connectify.account_access_audits_id_seq from public, anon, authenticated;
grant select, insert on connectify.account_access_audits to connectify_app;
grant usage, select on sequence connectify.account_access_audits_id_seq to connectify_app;

create policy connectify_app_audit_read
    on connectify.account_access_audits for select to connectify_app using (true);
create policy connectify_app_audit_insert
    on connectify.account_access_audits for insert to connectify_app with check (true);

comment on table connectify.account_access_audits is
    'Private Spring Boot account access audit; no credentials, passwords or payment secrets.';
