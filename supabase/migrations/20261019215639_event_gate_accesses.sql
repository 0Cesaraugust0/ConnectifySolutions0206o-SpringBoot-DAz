-- Event-scoped door access. No personal account is provisioned for a door.
set local lock_timeout = '5s';
set local statement_timeout = '30s';

-- Abort on legacy duplicates rather than silently changing an existing event code.
create unique index uq_events_gate_code_ci on connectify.events (lower(gate_access_code))
    where gate_access_code is not null;

create table connectify.event_gate_accesses (
    id bigint generated by default as identity primary key,
    event_id bigint not null references connectify.events(id),
    slot integer not null check (slot between 1 and 4),
    label varchar(60) not null,
    credential_hash varchar(100) not null,
    active boolean not null default true,
    access_version bigint not null default 1,
    updated_at timestamp(6) with time zone not null default now(),
    constraint uq_event_gate_slot unique (event_id, slot)
);

alter table connectify.tickets add column if not exists used_at timestamp(6) with time zone;
alter table connectify.tickets add column if not exists used_gate_name varchar(60);

alter table connectify.event_gate_accesses enable row level security;
revoke all on connectify.event_gate_accesses from public, anon, authenticated;
revoke all on sequence connectify.event_gate_accesses_id_seq from public, anon, authenticated;
grant select, insert, update, delete on connectify.event_gate_accesses to connectify_app;
grant usage, select on sequence connectify.event_gate_accesses_id_seq to connectify_app;
create policy connectify_app_gate_access on connectify.event_gate_accesses
    for all to connectify_app using (true) with check (true);

comment on table connectify.event_gate_accesses is
    'Up to four hashed, independently revocable door credentials per event. Accessed only by the Spring Boot server.';
comment on column connectify.tickets.used_at is 'Verified entry instant; NULL for legacy entries without a recorded time.';
comment on column connectify.tickets.used_gate_name is 'Door label at entry time; no password or credential.';
-- Legacy events.gate_password is not migrated or accepted as a fallback password.
